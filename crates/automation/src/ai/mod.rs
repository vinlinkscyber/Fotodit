/// Comprehensive result of an AI editing operation.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct AiResult {
    /// The user instruction that was processed.
    pub prompt: String,
    /// Visual perception of the document before editing.
    pub initial_scene: VisualScene,
    /// The structured editing plan that was resolved.
    pub plan: EditingPlan,
    /// Execution status, executed command IDs, and results.
    pub execution: ExecutionResult,
    /// Visual evaluation of the final modified composition.
    pub evaluation: EvaluationReport,
    /// Single-step undo token / revision tracking.
    pub revision: u64,
}

/// The unified AI Creative Editing Engine.
pub struct AiEngine {
    catalog: CommandCatalog,
    nl_engine: NaturalLanguageEngine,
    perception_engine: PerceptionEngine,
    layout_engine: LayoutEngine,
    eval_engine: EvaluationEngine,
    planner: Box<dyn AiPlanner>,
}

impl Default for AiEngine {
    fn default() -> Self {
        Self::new()
    }
}

impl AiEngine {
    /// Create a new AI engine with the default deterministic offline planner.
    pub fn new() -> Self {
        let catalog = CommandCatalog::new();
        Self {
            catalog: catalog.clone(),
            nl_engine: NaturalLanguageEngine::new(),
            perception_engine: PerceptionEngine::new(),
            layout_engine: LayoutEngine::new(),
            eval_engine: EvaluationEngine::new(),
            planner: Box::new(DeterministicRulePlanner::new(catalog)),
        }
    }

    /// Create an AI engine with a custom planner (e.g. cloud LLM or custom rules).
    pub fn with_planner(planner: Box<dyn AiPlanner>) -> Self {
        let catalog = CommandCatalog::new();
        Self {
            catalog: catalog.clone(),
            nl_engine: NaturalLanguageEngine::new(),
            perception_engine: PerceptionEngine::new(),
            layout_engine: LayoutEngine::new(),
            eval_engine: EvaluationEngine::new(),
            planner,
        }
    }

    /// Create an AI engine configured with the multi-provider bridge populated from environment variables.
    pub fn with_bridge_from_env() -> Self {
        let catalog = CommandCatalog::new();
        let config = ProviderConfig::from_env();
        let bridge = AiProviderBridge::new(config, catalog);
        Self::with_planner(Box::new(bridge))
    }

    /// Create an AI engine with an explicit provider configuration.
    pub fn with_provider_config(config: ProviderConfig) -> Self {
        let catalog = CommandCatalog::new();
        let bridge = AiProviderBridge::new(config, catalog);
        Self::with_planner(Box::new(bridge))
    }

    /// Generate an image using Pipeline 2 (Pollinations primary -> Gemini fallback).
    pub fn generate_image(&self, prompt: &str, width: u32, height: u32) -> Result<Vec<u8>, AiError> {
        let config = ProviderConfig::from_env();
        let bridge = AiProviderBridge::new(config, self.catalog.clone());
        bridge.generate_image(prompt, width, height)
    }

    /// Access the command catalog.
    pub fn catalog(&self) -> &CommandCatalog {
        &self.catalog
    }

    /// Access the layout engine.
    pub fn layout_engine(&self) -> &LayoutEngine {
        &self.layout_engine
    }

    /// Access the natural language engine.
    pub fn nl_engine(&self) -> &NaturalLanguageEngine {
        &self.nl_engine
    }

    /// Access the perception engine.
    pub fn perception_engine(&self) -> &PerceptionEngine {
        &self.perception_engine
    }

    /// Access the evaluation engine.
    pub fn eval_engine(&self) -> &EvaluationEngine {
        &self.eval_engine
    }

    /// Run full end-to-end intelligent editing on an open headless session.
    pub fn process_instruction(
        &self,
        headless: &mut Headless,
        prompt: &str,
        context: &mut AiContext,
    ) -> Result<AiResult, AiError> {
        // 1. Visual Perception: inspect active document structure and visual elements
        let doc_json = match headless.inspect(None) {
            Ok(json) => Some(json),
            Err(AutomationError::BadRequest(msg)) if msg.contains("no document open") => None,
            Err(other) => return Err(AiError::Automation(other)),
        };
        let initial_scene = match &doc_json {
            Some(json) => self.perception_engine.perceive(json),
            None => VisualScene::default(),
        };

        // 2. Natural Language Intelligence: understand intent and resolve targets
        let intent = self.nl_engine.parse_intent(prompt, &initial_scene, context)?;

        // If no document is open and intent cannot create one, report NoDocumentOpen
        if doc_json.is_none() && intent.category != IntentCategory::GraphicDesign {
            return Err(AiError::NoDocumentOpen);
        }

        // 3. Planning: produce a structured editing plan
        let mut plan = self.planner.plan(&intent, &initial_scene, context)?;

        // If no document is open, prepend a file.new step
        if doc_json.is_none() && !plan.steps.iter().any(|s| s.command == "file.new") {
            let [w, h] = plan.target_size.unwrap_or([1200, 1600]);
            plan.steps.insert(
                0,
                PlanStep {
                    command: "file.new".into(),
                    params: json!({
                        "width": w,
                        "height": h,
                        "background": "transparent"
                    }),
                    description: format!("Create new document ({w}x{h})"),
                },
            );
            plan.creates_document = true;
        }

        // 4. Command Intelligence: validate all plan steps against native command schemas
        for step in &plan.steps {
            self.catalog.validate_command(&step.command, &step.params)?;
        }

        // 5. Native Execution: execute transactionally with compound undo support
        let execution = ExecutionEngine::execute_plan(headless, &plan)?;

        // 6. Visual Evaluation: inspect resulting composition and verify goals
        let post_doc_json = headless.inspect(None).map_err(AiError::Automation)?;
        let final_scene = self.perception_engine.perceive(&post_doc_json);
        let evaluation = self.eval_engine.evaluate(&intent, &initial_scene, &final_scene, &execution);

        // Record interaction in context
        context.record_interaction(prompt.to_string(), plan.clone());

        let revision = post_doc_json.get("revision").and_then(Value::as_u64).unwrap_or(0);

        Ok(AiResult {
            prompt: prompt.to_string(),
            initial_scene,
            plan,
            execution,
            evaluation,
            revision,
        })
    }

    /// Plan an instruction without executing it (dry-run inspection).
    pub fn plan_instruction(
        &self,
        headless: &Headless,
        prompt: &str,
        context: &AiContext,
    ) -> Result<EditingPlan, AiError> {
        let doc_json = match headless.inspect(None) {
            Ok(json) => Some(json),
            Err(AutomationError::BadRequest(msg)) if msg.contains("no document open") => None,
            Err(other) => return Err(AiError::Automation(other)),
        };
        let initial_scene = match &doc_json {
            Some(json) => self.perception_engine.perceive(json),
            None => VisualScene::default(),
        };
        let intent = self.nl_engine.parse_intent(prompt, &initial_scene, context)?;
        if doc_json.is_none() && intent.category != IntentCategory::GraphicDesign {
            return Err(AiError::NoDocumentOpen);
        }
        let mut plan = self.planner.plan(&intent, &initial_scene, context)?;
        if doc_json.is_none() && !plan.steps.iter().any(|s| s.command == "file.new") {
            let [w, h] = plan.target_size.unwrap_or([1200, 1600]);
            plan.steps.insert(
                0,
                PlanStep {
                    command: "file.new".into(),
                    params: json!({
                        "width": w,
                        "height": h,
                        "background": "transparent"
                    }),
                    description: format!("Create new document ({w}x{h})"),
                },
            );
            plan.creates_document = true;
        }
        for step in &plan.steps {
            self.catalog.validate_command(&step.command, &step.params)?;
        }
        Ok(plan)
    }

    /// Run perception on active document.
    pub fn perceive_document(&self, headless: &Headless) -> Result<VisualScene, AiError> {
        let doc_json = headless.inspect(None).map_err(AiError::Automation)?;
        Ok(self.perception_engine.perceive(&doc_json))
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn end_to_end_design_generation_on_new_canvas() {
        let ai = AiEngine::new();
        let mut headless = Headless::trusted_local();
        let mut context = AiContext::new();

        let prompt = "Create an elegant wedding invitation";
        let res = ai.process_instruction(&mut headless, prompt, &mut context);
        assert!(res.is_ok(), "Expected success but got: {:?}", res.err());

        let result = res.unwrap();
        assert_eq!(result.plan.category, IntentCategory::GraphicDesign);
        assert!(result.execution.is_success);
        assert!(result.evaluation.intent_satisfied);
        assert!(result.evaluation.confidence_score >= 0.85);
        assert_eq!(context.prompt_history.len(), 1);
        assert_eq!(context.executed_plans.len(), 1);
    }

    #[test]
    fn end_to_end_photo_enhancement() {
        let ai = AiEngine::new();
        let mut headless = Headless::trusted_local();
        // First create a document
        headless
            .command_run("file.new", json!({"width": 800, "height": 600, "background": "white"}))
            .unwrap();

        let mut context = AiContext::new();
        let prompt = "Make this photograph look professional and enhance clarity";
        let res = ai.process_instruction(&mut headless, prompt, &mut context);
        assert!(res.is_ok(), "Expected success but got: {:?}", res.err());

        let result = res.unwrap();
        assert_eq!(result.plan.category, IntentCategory::PhotoEnhancement);
        assert!(result.execution.is_success);
        assert!(result.evaluation.intent_satisfied);
    }

    #[test]
    fn reject_photo_enhancement_without_document() {
        let ai = AiEngine::new();
        let mut headless = Headless::trusted_local();
        let mut context = AiContext::new();

        let prompt = "Make this photograph look professional";
        let res = ai.process_instruction(&mut headless, prompt, &mut context);
        assert!(matches!(res, Err(AiError::NoDocumentOpen)));
    }
}
