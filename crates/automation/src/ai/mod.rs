/// Error type for the AI creative editing system.
#[derive(Debug, thiserror::Error)]
pub enum AiError {
    #[error("intent parsing failed: {0}")]
    IntentError(String),
    #[error("visual perception failed: {0}")]
    PerceptionError(String),
    #[error("command resolution failed: {0}")]
    CommandResolutionError(String),
    #[error("parameter validation failed for '{command}': {message}")]
    ValidationError { command: String, message: String },
    #[error("planning failed: {0}")]
    PlanningError(String),
    #[error("execution failed at step {step} ('{command}'): {error}")]
    ExecutionError { step: usize, command: String, error: String },
    #[error("evaluation failed: {0}")]
    EvaluationError(String),
    #[error("automation engine error: {0}")]
    Automation(#[from] AutomationError),
    #[error("no document open")]
    NoDocumentOpen,
}

/// A structured editing plan generated by the AI planner.
#[derive(Clone, Debug, PartialEq, Serialize, Deserialize)]
pub struct EditingPlan {
    /// Human-readable title of the operation.
    pub title: String,
    /// Detailed rationale explaining why these operations achieve the user's intent.
    pub rationale: String,
    /// High-level intent category.
    pub category: IntentCategory,
    /// Ordered list of validated native command steps.
    pub steps: Vec<PlanStep>,
    /// Whether this plan requires creating a new document.
    pub creates_document: bool,
    /// Target document dimensions (if new or resized).
    pub target_size: Option<[u32; 2]>,
}

/// Conversational context tracking previous instructions and active document state.
#[derive(Clone, Debug, Default, Serialize, Deserialize)]
pub struct AiContext {
    /// History of natural language prompts submitted in this session.
    pub prompt_history: Vec<String>,
    /// History of executed plans.
    pub executed_plans: Vec<EditingPlan>,
    /// User preferences (e.g. favorite fonts, brand color palette).
    pub preferences: UserPreferences,
    /// Active target layer name or id referenced in conversational flow.
    pub active_target: Option<String>,
}

impl AiContext {
    /// Create fresh context.
    pub fn new() -> Self {
        Self::default()
    }

    /// Record a completed prompt and plan. History is bounded to the most
    /// recent `MAX_HISTORY` turns so long sessions stay within prompt budget.
    pub fn record_interaction(&mut self, prompt: String, plan: EditingPlan) {
        const MAX_HISTORY: usize = 16;
        self.prompt_history.push(prompt);
        self.executed_plans.push(plan);
        if self.prompt_history.len() > MAX_HISTORY { self.prompt_history.remove(0); }
        if self.executed_plans.len() > MAX_HISTORY { self.executed_plans.remove(0); }
    }
}

